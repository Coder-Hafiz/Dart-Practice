// রিলেশনাল অপারেটরস (Relational Operators)
// এই অপারেটরগুলো দুইটি মানের মধ্যে তুলনা করতে ব্যবহৃত হয়।

void main(){
  int a = 10;
  int b = 5;
  print(a == b);   // false
  print(a != b);   // true
  print(a > b);    // true
  print(a < b);    // false
  print(a >= b);   // true
  print(a <= b);   // false
}