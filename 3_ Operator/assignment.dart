// অ্যাসাইনমেন্ট অপারেটরস (Assignment Operators)
// এই অপারেটরগুলো ভেরিয়েবলে মান অ্যাসাইন করতে ব্যবহৃত হয়।

void main() {
  int a = 10;
  int b = 5;
  print("addition is: ${a += b}"); // a = a + b ->15
  print("substraction is: ${a -= b}"); // a = a - b -> 10
  print("multiplication is: ${a *= b}"); // a = a * b -> 50
  print("division is: ${a = b}"); // a = a / b -> 10.0
  print("modulus is: ${a %= b}"); // a = a % b -> 0
}
